function goToView(name){
  document.querySelectorAll('.view').forEach(v=> v.classList.toggle('active', v.id === 'view-'+name));
  document.querySelectorAll('.navbtn').forEach(b=> b.classList.toggle('active', b.dataset.view === name));
  window.scrollTo(0,0);
}
document.querySelectorAll('.navbtn').forEach(b=> b.addEventListener('click', ()=> goToView(b.dataset.view)));
document.querySelectorAll('[data-goto]').forEach(b=> b.addEventListener('click', ()=> goToView(b.dataset.goto)));

/* ---- Build pattern list ---- */
const list = document.getElementById('list');

DATA.forEach(([pname, qs], pi)=>{
  const patDiv = document.createElement('div');
  patDiv.className = 'pattern';
  patDiv.dataset.pattern = pname.toLowerCase();
  const emoji = PATTERN_EMOJI[pname.toLowerCase()] || '📌';

  const head = document.createElement('div');
  head.className = 'pattern-head';
  head.innerHTML = `<span class="chev">▶</span><span class="pemoji">${emoji}</span><span class="name">${pname}</span><span class="count" data-count></span>`;
  head.addEventListener('click', ()=> patDiv.classList.toggle('open'));
  patDiv.appendChild(head);

  const miniBar = document.createElement('div');
  miniBar.className = 'mini-bar';
  miniBar.innerHTML = '<span data-minifill style="width:0%"></span>';
  patDiv.appendChild(miniBar);

  const qlist = document.createElement('div');
  qlist.className = 'qlist';

  qs.forEach(([qname, links], qi)=>{
    const id = 'q_'+pi+'_'+qi;
    const xp = xpForQuestion(qname);
    const row = document.createElement('div');
    row.className = 'q';
    row.dataset.xp = xp;
    row.dataset.search = (qname + ' ' + pname).toLowerCase();
    const isDone = !!solved[id];
    if(isDone) row.classList.add('done');

    const linksHtml = links.length
      ? `<div class="links">${links.map((l,i)=>`<a href="${l}" target="_blank" rel="noopener">${links.length>1?'Link '+(i+1):'Solve ↗'}</a>`).join('')}</div>`
      : '';

    row.innerHTML = `<input type="checkbox" id="${id}" ${isDone?'checked':''}>
      <label for="${id}"><span class="qname">${qname}<span class="xp-tag">+${xp} XP</span></span>${linksHtml}</label>`;

    row.querySelector('input').addEventListener('change', (e)=>{
      solved[id] = e.target.checked;
      row.classList.toggle('done', e.target.checked);
      saveSolved();
      if(e.target.checked){ bumpStreak(); showToast(`+${xp} XP`); }
      updateCounts(true);
    });

    qlist.appendChild(row);
  });

  patDiv.appendChild(qlist);
  patDiv.dataset.total = qs.length;
  list.appendChild(patDiv);
});

let lastLevelIdx = null;

function updateCounts(announce){
  let done=0, total=0, xpEarned=0, patternsComplete=0;
  const quickData = [];
  document.querySelectorAll('#list .pattern').forEach((patDiv, pi)=>{
    const rows = patDiv.querySelectorAll('.q');
    const t = rows.length;
    let d = 0;
    rows.forEach(r=>{ if(r.classList.contains('done')){ d++; xpEarned += parseInt(r.dataset.xp,10)||0; } });
    total += t; done += d;
    patDiv.querySelector('[data-count]').textContent = `${d}/${t}`;
    const pct = t ? Math.round(d/t*100) : 0;
    patDiv.querySelector('[data-minifill]').style.width = pct + '%';
    const isComplete = t>0 && d===t;
    patDiv.classList.toggle('complete', isComplete);
    if(isComplete) patternsComplete++;
    quickData.push({name: DATA[pi][0], emoji: PATTERN_EMOJI[DATA[pi][0].toLowerCase()]||'📌', d, t, pct});
  });

  document.getElementById('statSolved').textContent = `${done}/${total}`;
  const opct = total ? Math.round(done/total*100) : 0;
  document.getElementById('statPct').textContent = opct + '%';
  document.getElementById('statPatterns').textContent = `${patternsComplete}/${DATA.length}`;

  const lvlIdx = levelForXp(xpEarned);
  const lvl = LEVELS[lvlIdx];
  const nextLvl = LEVELS[lvlIdx+1];
  document.getElementById('levelName').textContent = lvl.name;
  document.getElementById('avatarInitial').textContent = 'L'+(lvlIdx+1);
  document.getElementById('xpText').textContent = `${xpEarned} XP`;
  document.getElementById('xpCaptionLeft').textContent = `Level ${lvlIdx+1}`;
  if(nextLvl){
    const span = nextLvl.xp - lvl.xp;
    const into = xpEarned - lvl.xp;
    document.getElementById('xpBarFill').style.width = Math.min(100, Math.round(into/span*100)) + '%';
    document.getElementById('xpCaptionRight').textContent = `${nextLvl.xp - xpEarned} XP to ${nextLvl.name}`;
  } else {
    document.getElementById('xpBarFill').style.width = '100%';
    document.getElementById('xpCaptionRight').textContent = 'Max level reached';
  }
  if(announce && lastLevelIdx !== null && lvlIdx > lastLevelIdx){
    showToast(`🎉 Level up! You're now ${lvl.name}`, 'level');
  }
  lastLevelIdx = lvlIdx;

  document.getElementById('streakChip').textContent = `🔥 ${meta.streak||0}`;

  const stats = {done, total, patternsComplete, totalPatterns: DATA.length};
  const unlockedList = [];
  BADGES.forEach(b=>{
    const unlocked = b.test(stats);
    if(unlocked && announce && !meta.unlockedBadges.includes(b.id)){
      meta.unlockedBadges.push(b.id);
      showToast(`🏅 Badge unlocked: ${b.label}`, 'badge');
    }
    if(unlocked) unlockedList.push(b);
  });

  const fullGrid = document.getElementById('badgeGridFull');
  fullGrid.innerHTML = '';
  BADGES.forEach(b=>{
    const unlocked = b.test(stats);
    const el = document.createElement('div');
    el.className = 'badge' + (unlocked?' unlocked':'');
    el.innerHTML = `<div class="icon">${b.icon}</div><span class="blabel">${b.label}</span>`;
    fullGrid.appendChild(el);
  });

  const dashRow = document.getElementById('badgeRowDash');
  dashRow.innerHTML = '';
  BADGES.slice(0,6).forEach(b=>{
    const unlocked = b.test(stats);
    const el = document.createElement('div');
    el.className = 'badge' + (unlocked?' unlocked':'');
    el.innerHTML = `<div class="icon">${b.icon}</div><span class="blabel">${b.label}</span>`;
    dashRow.appendChild(el);
  });

  const qlDiv = document.getElementById('quickList');
  qlDiv.innerHTML = '';
  quickData.forEach((q, pi)=>{
    const row = document.createElement('div');
    row.className = 'qk-row';
    row.addEventListener('click', ()=>{
      goToView('patterns');
      const target = document.querySelectorAll('#list .pattern')[pi];
      target.classList.add('open');
      target.scrollIntoView({behavior:'smooth', block:'start'});
    });
    row.innerHTML = `<span class="qk-emoji">${q.emoji}</span><span class="qk-name">${q.name}</span><div class="qk-bar"><span style="width:${q.pct}%"></span></div><span class="qk-count">${q.d}/${q.t}</span>`;
    qlDiv.appendChild(row);
  });

  saveMeta();
}
