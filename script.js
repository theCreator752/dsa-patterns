document.getElementById('search').addEventListener('input', (e)=>{
  const term = e.target.value.trim().toLowerCase();
  let anyVisible = false;
  document.querySelectorAll('#list .pattern').forEach(patDiv=>{
    let patternMatch = patDiv.dataset.pattern.includes(term);
    let hasVisibleQ = false;
    patDiv.querySelectorAll('.q').forEach(row=>{
      const match = term === '' || patternMatch || row.dataset.search.includes(term);
      row.classList.toggle('hidden', !match);
      if(match) hasVisibleQ = true;
    });
    patDiv.classList.toggle('hidden', !hasVisibleQ);
    if(hasVisibleQ){ anyVisible = true; if(term !== '') patDiv.classList.add('open'); }
  });
  document.getElementById('emptyMsg').classList.toggle('hidden', anyVisible || term==='');
});

document.getElementById('expandAll').addEventListener('click', ()=>{
  document.querySelectorAll('#list .pattern').forEach(p=>p.classList.add('open'));
});
document.getElementById('collapseAll').addEventListener('click', ()=>{
  document.querySelectorAll('#list .pattern').forEach(p=>p.classList.remove('open'));
});
